// Scoring Calibration -- retuned alongside kMinPossessionSeconds's pace
// fix above: restoring realistic NBA pace closed most, but not all, of
// this engine's average-score gap (measured via main.cpp's identical
// possession model, mirrored byte-for-byte here: a 40-game CPU batch at
// the corrected pace still averaged only ~97 points/team against a real
// ~105-115 target). tuning.contested_iso_fg_pct_penalty and
// kFtSubstitutionProbReduction apply on effectively every shot attempt, so
// both were over-penalizing offensive success across the board rather
// than reflecting a single specific real effect; each is trimmed here
// rather than removed, so the branches these represent (fully-contested
// looks, the FT-trip made-prob offset) still suppress scoring relative to
// an unguarded look -- just not enough to single-handedly explain a
// ~74-90-point game. Mirrors main.cpp exactly.
// tuning.paint_finish_fg_pct_bonus/tuning.open_shot_bonus_multiplier/tuning.contested_iso_fg_pct_penalty
// DELIBERATELY DIVERGE from main.cpp's identically-named constants here --
// the one intentional exception to this file's "mirrors main.cpp exactly"
// convention, and documented as such everywhere it matters. Root cause:
// this kernel's off_gravity/def_gravity (see sample_on_court_gravity above)
// samples the top-5-by-minutes roster slots every possession, because the
// GPU batch engine has no per-possession fatigue/substitution model at
// all (a deliberate, long-standing performance tradeoff -- see this file's
// module comment). main.cpp's ActiveLineup::get_current_gravity(), by
// contrast, reflects whichever 5 players are ACTUALLY on the floor at that
// moment, including lower-spacing bench players subbed in once starters
// tire. So this kernel's off_gravity runs systematically higher than
// main.cpp's own possession-weighted average across a full 48 minutes --
// and since Node 1's now-softened weights above make the archetype's flat
// additive bonus (kPaintDominantOpennessBonus etc.) relatively more
// dominant, that structural gap compounded into a measured ~9-10 point/
// team GPU-only scoring inflation once Node 1 was softened (main.cpp
// stayed correctly calibrated at the same settings; confirmed empirically
// -- a 200-game CPU batch held ~108.85 pts/team throughout, while the GPU
// batch drifted to ~118 with main.cpp's own Node 2 values). Trimming Node
// 1's compounding-sensitivity weights was this task's actual, explicit
// ask; this file's Node 2 spread constants are retuned independently
// (smaller bonus, and the "open shot" multiplier flipped to a mild
// penalty) specifically to offset that GPU-only structural inflation, so
