#define CUDA_CHECK(call)                                                          \
    do {                                                                          \
        cudaError_t _cuda_err = (call);                                           \
        if (_cuda_err != cudaSuccess) {                                           \
            if (is_toolchain_mismatch(_cuda_err)) {                               \
                warn_toolchain_mismatch(_cuda_err);                               \
            } else {                                                              \
                std::cerr << "[CUDA] " #call " failed: "                          \
                          << cudaGetErrorString(_cuda_err)                        \
                          << " (" << __FILE__ << ":" << __LINE__ << ")" << std::endl; \
            }                                                                     \
            return;                                                               \
        }                                                                         \
    } while (0)

// A PTX/toolchain version mismatch surfaces through a handful of distinct
// cudaError_t codes depending on exactly where the driver's JIT compiler (or
// the SASS-image loader, if no compatible SASS was embedded) gives up:
//   - cudaErrorInvalidPtx: the driver's PTX JIT rejected the embedded PTX,
//     usually because it was emitted by a newer nvcc than the driver's
//     compiler understands.
//   - cudaErrorNoKernelImageForDevice / cudaErrorInvalidDeviceFunction: no
//     SASS or PTX the driver can use was found for this GPU at all.
//   - cudaErrorInsufficientDriver: the installed driver is older than the
//     minimum required by the CUDA runtime the binary was built against.
bool is_toolchain_mismatch(cudaError_t err) {
    return err == cudaErrorInvalidPtx ||
           err == cudaErrorNoKernelImageForDevice ||
           err == cudaErrorInvalidDeviceFunction ||
           err == cudaErrorInsufficientDriver;
}

void warn_toolchain_mismatch(cudaError_t err) {
    int driver_version = 0;
    int runtime_version = 0;
    cudaDriverGetVersion(&driver_version);
    cudaRuntimeGetVersion(&runtime_version);

    std::cerr << "\n[CUDA] WARNING: GPU driver / CUDA toolkit version mismatch.\n"
              << "  CUDA error       : " << cudaGetErrorString(err) << "\n"
              << "  Installed driver supports CUDA runtime up to : "
              << (driver_version / 1000) << "." << ((driver_version % 100) / 10) << "\n"
              << "  This binary was built against CUDA runtime   : "
              << (runtime_version / 1000) << "." << ((runtime_version % 100) / 10) << "\n"
              << "  Your NVIDIA driver is older than the CUDA toolchain used to compile\n"
              << "  this kernel, so the driver could not JIT the embedded PTX (or find a\n"
              << "  matching precompiled SASS image) for your GPU.\n"
              << "  Fix: update your NVIDIA driver, or rebuild with an older CUDA Toolkit\n"
              << "  / with CMAKE_CUDA_ARCHITECTURES set to '<arch>-real' for your GPU so\n"
              << "  no PTX JIT step is required.\n"
              << "  Falling back gracefully -- GPU Monte Carlo simulation skipped.\n"
              << std::endl;
}

// Minimal RAII wrapper around a device allocation. Frees automatically on
// scope exit (including early returns after a failed CUDA_CHECK), so the
// host wrapper below never needs a manual cudaFree() on any error path.
template <typename T>
class DeviceBuffer {
public:
    DeviceBuffer() = default;
    ~DeviceBuffer() { reset(); }
    DeviceBuffer(const DeviceBuffer&) = delete;
    DeviceBuffer& operator=(const DeviceBuffer&) = delete;

    cudaError_t allocate(size_t count) {
        reset();
        return cudaMalloc(reinterpret_cast<void**>(&ptr_), count * sizeof(T));
    }
    cudaError_t upload(const T* host_data, size_t count) {
        return cudaMemcpy(ptr_, host_data, count * sizeof(T), cudaMemcpyHostToDevice);
    }
    cudaError_t download(T* host_data, size_t count) const {
        return cudaMemcpy(host_data, ptr_, count * sizeof(T), cudaMemcpyDeviceToHost);
    }
    T* get() const { return ptr_; }
    void reset() {
        if (ptr_) {
            cudaFree(ptr_);
            ptr_ = nullptr;
        }
    }

private:
    T* ptr_ = nullptr;
};

// Reverses a roster index when `reversed` (garbage time): walks the bottom
// (real bench, by minutes) of the array instead of the top (real starters).
__device__ __forceinline__ int roster_idx(int i, int n, bool reversed) {
    return reversed ? (n - 1 - i) : i;
}

// Samples one team's live floor-spacing gravity for a single possession: the
// Box-Cox 3PT spacing transform (fg3_pct * (fg3a + 1)^0.2671) for each of the
// up to kMaxOnCourtPlayers starters (or, in garbage time, the deepest
// bench), weighted by positional spacing weight. Deliberately DETERMINISTIC
// -- mirrors main.cpp's ActiveLineup::get_current_gravity() exactly (same
// formula, no per-possession noise). A prior version of this function
// injected a +/-15% (1 std dev) "game-to-game shooting variance" term via
// curand_normal, which main.cpp never had; because this value feeds Node
// 1's THRESHOLD-gated paint_openness branch selection (kPaintOpenThreshold/
// kPaintLockedThreshold), that asymmetric-payoff kink meant the noise didn't
// just add symmetric variance -- it shifted the GPU engine's EXPECTED shot-
// quality distribution upward relative to the CPU engine's (a Jensen's-
// inequality-style bias), producing a persistent, measurable CPU/GPU
// scoring gap (found while investigating this task's blowout-compounding
// recalibration: the CPU/GPU average-score gap widened from ~3.5 to ~6.75
// points/team once Node 1's weights were softened, moving values closer to
// those same thresholds). Removed entirely rather than added to main.cpp,
// since eliminating this spurious compounding source is directly in scope
// for this same calibration pass.
__device__ __forceinline__ float sample_on_court_gravity(const float* fg3_pct,
                                                           const float* fg3a,
                                                           const float* position_weight,
                                                           int on_court_n,
                                                           int total_n,
                                                           bool reversed) {
    float gravity = 0.0f;
    for (int i = 0; i < on_court_n; ++i) {
        int ri = roster_idx(i, total_n, reversed);
        float spacing = fg3_pct[ri] * powf(fg3a[ri] + 1.0f, 0.2671f);
        gravity += spacing * position_weight[ri];
    }
    return gravity;
}

// Simulates one offensive possession as a discrete-event state machine and
// adds any points scored to `score`. The shooter is picked via a
// usage-rate-weighted draw over the full offense rotation using a
// branch-free running-select (every thread executes the same fixed number
// of iterations, `off_n`, regardless of the random draw) -- unchanged from
// the prior model. The PRIMARY DEFENDER is then the defense's roster entry
// at the shooter's own rotation index (both rosters are pre-sorted by real
// minutes played, so this is a genuine minutes/usage-rank-matched matchup
// assignment without needing spatial court coordinates).
//
// `ml_prob_bias` is the ML-calibrated per-possession shot-probability shift
// for the offense currently at bat (positive favors this offense, negative
// disfavors it -- see kMlMarginToProbShift above); `off_fatigue_prob_penalty`
// is the back-to-back fatigue penalty. Both are folded into whichever
// branch's made-shot probability ultimately resolves, exactly as the prior
// single-formula model applied them to `final_prob`.
//
// `star_idx` / `hot_hand_boost` implement the "Big Match Hot Hands / Star
// Momentum" effect: for a marquee/high-stakes matchup the caller has already
// identified (see hot_hand_boost usage in run_cuda_monte_carlo below),
// `off_usage[star_idx]` gets multiplied by `hot_hand_boost` both when
// picking the shooter (more of the offense runs through them) and, if they
// end up as the shooter, on their effective made-shot probability. A
// neutral 1.0 multiplier is an exact no-op on both.
//
// `off_archetype` is this offense's Team Tactical Archetype (Macro DNA
// Layer -- see the comment block above kArchetypeBalanced and
// run_cuda_monte_carlo's derive_team_archetype()/has_archetype_override
// resolution below): a baseline Node 0/Node 2 tendency bias applied before
// the situational modifiers (shot clock urgency/desperation/protect lead)
// get their turn. kArchetypeBalanced (0) is a no-op.
//
// `off_shooting_variance`/`def_intensity_variance` are this offense's/
// defense's own Game-to-Game Stochastic Variance draws (see the comment
// block above tuning.game_variance_std_dev) -- fixed for this entire game (drawn
// once per thread in monte_carlo_matchup_kernel, not here), scaling this
// offense's real shooting efficiency/floor-spacing and this defense's real
// rim-protection/help-IQ/floor-spacing respectively. 1.0 is a no-op.
//
// `def_personal_fouls_rate` is the defense's per-player real personal
// fouls/game array (indexed by the matched defender), feeding the
// Conditional Foul & Free Throw Mechanics Engine's Shooting/Non-Shooting
// foul probabilities (see the comment block above kNeutralPersonalFouls).
// `def_team_fouls_this_q` is the defense's own real per-quarter team-foul
// counter (mutable, owned by the caller -- monte_carlo_matchup_kernel
// below -- and reset there at each real quarter boundary): incremented on
// every Non-Shooting Foul, and checked against kTeamFoulsBonusThreshold to
// decide whether that foul awards bonus free throws.
//
// `def_on_ball_defense` is the defense's per-player on-ball defense rating
// array (indexed by the matched defender). `def_help_defense_iq_avg` /
// `def_rim_protection_best` are team-wide aggregates (real steals/game mean
// and real blocks/game max across the defense's top-5 rotation --
// GPURoster::help_defense_iq_avg / rim_protection_best) applied regardless
// of who the primary defender is, modeling forced turnovers and helpside
// rim deterrence. `off_reb_gravity_best` (the offense's best real
// offensive rebounder) / `def_reb_gravity_avg` (the defense's team-wide
// real defensive-rebounding activity) drive the Offensive Rebound Loop
// below: a missed/blocked shot no longer automatically surrenders the ball.
// `off_ft_pct` feeds and-1/shooting-foul free-throw resolution (see the
// Free Throw / And-1 Resolution comment block above). `garbage_time` --
// true only when this exact possession is both late (possession index) AND
// during a real blowout margin -- reverses which end of each SoA array is
// read (real bench instead of real starters/top-usage players) via
// `roster_idx()` and disables `hot_hand_boost` entirely; the CALLER
// (monte_carlo_matchup_kernel) is responsible for also swapping the
// starter/bench variants of `def_help_defense_iq_avg` etc. before this call
// when `garbage_time` is true.
__device__ __forceinline__ void simulate_possession(const float* off_fg3_pct,
                                                      const float* off_fg3a,
                                                      const float* off_fg_pct,
                                                      const float* off_ft_pct,
                                                      const float* off_drive_gravity,
                                                      const float* off_usage,
                                                      const float* off_position_weight,
                                                      int off_n,
                                                      int off_star_idx,
                                                      const float* def_fg3_pct,
                                                      const float* def_fg3a,
                                                      const float* def_position_weight,
                                                      const float* def_on_ball_defense,
                                                      const float* def_personal_fouls_rate,
                                                      int def_n,
                                                      float def_help_defense_iq_avg,
                                                      float def_rim_protection_best,
                                                      float off_playmaking_gravity_avg,
                                                      float off_reb_gravity_best,
                                                      float def_reb_gravity_avg,
                                                      float ml_prob_bias,
                                                      float hot_hand_boost,
                                                      bool garbage_time,
                                                      float off_fatigue_prob_penalty,
                                                      float off_fatigue_gravity_mult,
                                                      int off_deficit,
                                                      int off_archetype,
                                                      float off_shooting_variance,
                                                      float def_intensity_variance,
                                                      float off_momentum_edge,
                                                      int def_rim_anchor_idx,
                                                      int* def_rim_anchor_fouls,
                                                      int* def_team_fouls_this_q,
                                                      EngineTuningParams tuning,
                                                      int game_end_seconds,
                                                      int* total_game_seconds,
                                                      curandState* rand_state,
                                                      int* score) {
    // Shared game clock: draw this possession's real, variable length
    // (mirrors main.cpp's PossessionEngine time_dist(14, 22)) and consume it
    // from the SAME clock both teams share. Hard-capped so the game can
    // never run past `game_end_seconds` (buzzer-beater adjustment) -- the
    // current PERIOD's real end-of-clock boundary (kGameDurationSeconds for
    // regulation, extended by tuning.ot_period_seconds per overtime period
    // by the caller -- see monte_carlo_matchup_kernel), not a hardcoded
    // constant, so a possession can no longer overrun into a following OT
    // period any more than the old code let one overrun the final buzzer.
    if (*total_game_seconds >= game_end_seconds) return;

    // Desperation-mode pace-up: real, symmetric, condition-triggered (fires
    // for WHICHEVER team is trailing, not a specific team) -- mirrors
    // garbage_time's own trigger convention. A team that's genuinely still
    // in catch-up range (behind, but not so far gone that garbage_time has
    // already kicked in) late in the game pushes tempo -- quick 3s, fast
    // breaks -- instead of bleeding the shot clock, a well-documented real
    // coaching behavior. Only shortens THIS offense's own possession length;
    // doesn't touch shot selection/probabilities (those already react to
    // the game state via garbage_time/hot_hand_boost).
    bool desperation = !garbage_time
        && (*total_game_seconds >= kDesperationStartSeconds)
        && (off_deficit > 0) && (off_deficit < kGarbageTimeMarginThreshold);
    // Protect Lead / Burn Clock (Macro Tactical State Modifier) -- see the
    // comment block above kProtectLeadMinPossessionSeconds.
    bool protect_lead = !garbage_time
        && (*total_game_seconds >= kDesperationStartSeconds)
        && (off_deficit < 0) && (-off_deficit < kGarbageTimeMarginThreshold);
    // Game Momentum & Scoring Runs (Macro/Micro Integration) -- unlike
    // Desperation/Protect Lead above (gated to the final 3 minutes),
    // momentum can strike any time a team goes cold relative to the
    // opponent's own recent scoring rate (off_momentum_edge, an
    // exponentially-decayed recent-points differential owned by the
    // caller -- see monte_carlo_matchup_kernel). A team getting run on
    // slows down to stop the bleeding rather than compounding the damage
    // with quick, panicked possessions. Skipped when a more specific
    // late-game state already applies. Mirrors main.cpp exactly.
    bool cold_streak = !desperation && !protect_lead && !garbage_time
        && (off_momentum_edge < -tuning.momentum_cold_threshold);
    int min_poss = desperation ? kDesperationMinPossessionSeconds
                    : protect_lead ? kProtectLeadMinPossessionSeconds
                    : cold_streak ? tuning.momentum_cold_pace_min_seconds
                    : tuning.min_possession_seconds;
    int max_poss = desperation ? kDesperationMaxPossessionSeconds
                    : protect_lead ? kProtectLeadMaxPossessionSeconds
                    : cold_streak ? tuning.momentum_cold_pace_max_seconds
                    : tuning.max_possession_seconds;
    int possession_time = min_poss +
        static_cast<int>(curand(rand_state) % (max_poss - min_poss + 1));
    if (*total_game_seconds + possession_time > game_end_seconds) {
        possession_time = game_end_seconds - *total_game_seconds;
        if (possession_time <= 0) return;
    }
    *total_game_seconds += possession_time;

    const float effective_hot_hand_boost = garbage_time ? 1.0f : hot_hand_boost;

    // Clutch Factor & Overtime Desperation Boost -- see the comment block
    // above tuning.clutch_time_margin_threshold in cuda_simulator.cuh.
    // Computed the same way as main.cpp's identical mechanic: real NBA
    // "clutch time" (final tuning.clutch_time_remaining_seconds_threshold
    // of the 4th quarter OR any overtime period, score within
    // tuning.clutch_time_margin_threshold) reuses off_deficit (already
    // available here) rather than a separate score_off/score_def pair.
    // Independent of (and stacks with) Game Momentum & Scoring Runs --
    // one is clock/margin-driven, the other recent-scoring-driven.
    int current_period = compute_period(*total_game_seconds, tuning.ot_period_seconds);
    int period_elapsed_secs = *total_game_seconds - period_start_seconds(current_period, tuning.ot_period_seconds);
    int remaining_period_secs = period_length_seconds(current_period, tuning.ot_period_seconds) - period_elapsed_secs;
    bool is_overtime = current_period > kNumRegulationQuarters;
    bool clutch_time = (is_overtime || current_period == kNumRegulationQuarters)
        && static_cast<float>(remaining_period_secs) <= tuning.clutch_time_remaining_seconds_threshold
        && fabsf(static_cast<float>(off_deficit)) <= tuning.clutch_time_margin_threshold;
    // "Boost Star Player Usage Rates (Node 0)": clutch time stacks a
    // further multiplier onto the SAME star-usage mechanism hot_hand_boost
    // already uses, rather than a second, parallel star-identification
    // path. A neutral 1.0 when not in clutch time is an exact no-op.
    const float effective_star_usage_boost = effective_hot_hand_boost * (clutch_time ? tuning.clutch_star_usage_mult : 1.0f);

    // Game-to-Game Stochastic Variance -- this defense's own fixed-for-
    // this-game draw (see the comment block above tuning.game_variance_std_dev),
    // scaling its real rim-protection/help-IQ activity for the whole game.
    // Shadows the raw parameters so every downstream use below (including
    // the turnover trigger immediately following) already sees the
    // game-adjusted value -- mirrors main.cpp's def_rim_protect/def_help_iq
    // local variables exactly.
    // Foul Trouble Tracking -- team-wide "defensive intensity" (help IQ)
    // debuff reuses the ALREADY-tracked per-quarter team-foul-bonus state
    // (def_team_fouls_this_q) rather than a new counter: once a team
    // enters the real NBA bonus this quarter, it's genuinely playing more
    // cautious, foul-averse team defense for the rest of it. The rim-
    // protection debuff is the truly PER-PLAYER mechanic, applied below
    // via def_rim_anchor_idx/def_rim_anchor_fouls (see the comment block
    // above GPURoster::rim_anchor_idx in cuda_simulator.cuh). Mirrors
    // main.cpp's foul_trouble_rim_mult()/def_team_fouls_this_q reuse
    // exactly.
    float foul_trouble_rim_mult = 1.0f;
    if (*def_rim_anchor_fouls >= tuning.foul_trouble_severe_threshold) {
        foul_trouble_rim_mult = tuning.foul_trouble_rim_protect_severe_mult;
    } else if (*def_rim_anchor_fouls >= tuning.foul_trouble_threshold) {
        foul_trouble_rim_mult = tuning.foul_trouble_rim_protect_mult;
    }
    float def_rim_protection_best_eff = def_rim_protection_best * def_intensity_variance * foul_trouble_rim_mult;
    float def_help_defense_iq_avg_eff = def_help_defense_iq_avg * def_intensity_variance
        * ((*def_team_fouls_this_q >= kTeamFoulsBonusThreshold) ? tuning.foul_trouble_help_iq_mult : 1.0f);

    // 2. Defensive Suppression / Turnover Trigger: "Turnover / Bad Shot" --
    // checked ONCE, against the possession's real ball-handler, before any
    // shot is attempted. A follow-up put-back attempt after an offensive
    // rebound (see the loop below) is a live-ball scramble, not a fresh
    // "bring the ball up" situation, so it isn't re-exposed to a second,
    // independent turnover roll.
    {
        int first_rank = (!garbage_time && off_star_idx >= 0 && off_star_idx < off_n) ? off_star_idx : 0;
        int first_shooter = roster_idx(first_rank, off_n, garbage_time);
        float first_on_ball_defense = def_on_ball_defense[roster_idx(first_shooter % def_n, def_n, garbage_time)];
        float turnover_prob = kBaseTurnoverRate
            + kTurnoverPerHelpIqPoint * (def_help_defense_iq_avg_eff - kNeutralHelpDefenseIq)
            + kTurnoverPerOnBallDefPoint * (first_on_ball_defense - kNeutralOnBallDefense);
        turnover_prob = fminf(kMaxTurnoverProb, fmaxf(kMinTurnoverProb, turnover_prob));
        if (curand_uniform(rand_state) < turnover_prob) {
            return;
        }
    }

    const float shift = ml_prob_bias + off_fatigue_prob_penalty;

    // Floor-spacing gravity is a property of this possession's defensive
    // coverage, not each individual shot attempt within it -- sampled once
    // here (not per put-back attempt) so the offensive-rebound loop doesn't
    // inadvertently re-roll it 2-3x.
    int off_on_court = min(off_n, kMaxOnCourtPlayers);
    int def_on_court = min(def_n, kMaxOnCourtPlayers);
    // Game-to-Game Stochastic Variance -- this offense's/defense's own
    // fixed-for-this-game draws (see the comment block above
    // tuning.game_variance_std_dev).
    float off_gravity = sample_on_court_gravity(off_fg3_pct, off_fg3a, off_position_weight, off_on_court, off_n, garbage_time)
                         * off_fatigue_gravity_mult * off_shooting_variance;
    float def_gravity = sample_on_court_gravity(def_fg3_pct, def_fg3a, def_position_weight, def_on_court, def_n, garbage_time)
                         * def_intensity_variance;

    // 3. Shot Selection + Offensive Rebound Loop: each attempt re-runs
    // Matchup Selection (a fresh usage-weighted shooter/defender draw,
    // representing where the ball ends up after a scramble or kick-out)
    // and Shot Selection (catch-and-shoot "Kick-out to Open 3PT" vs.
    // isolation/drive -> Blow-by vs. Rim-Protection-Contested) -> make/miss
    // -> and-1/shooting-foul FT resolution. A miss/block with no foul no
    // longer ends the possession outright: the offense's real best
    // offensive rebounder vs. the defense's real team-wide defensive-
    // rebounding activity determines whether they keep the ball for
    // another look, bounded to kMaxPossessionAttempts total attempts.
    for (int attempt = 0; attempt < kMaxPossessionAttempts; ++attempt) {
        // 1. Matchup Selection. Iterates rotation RANK (i, usage-weighted
        // draw order); `roster_idx()` maps each rank to the actual array
        // index -- top-down normally, bottom-up (real bench) in garbage
        // time. `shooter`/`defender` end up holding real array indices for
        // all the per-player lookups below.
        float total_weight = 0.0f;
        for (int i = 0; i < off_n; ++i) {
            int ri = roster_idx(i, off_n, garbage_time);
            float w = fmaxf(5.0f, off_usage[ri]);
            if (!garbage_time && i == off_star_idx) w *= effective_star_usage_boost;
            total_weight += w;
        }

        float pick = curand_uniform(rand_state) * total_weight;
        float cumulative = 0.0f;
        int shooter_rank = -1;
        for (int i = 0; i < off_n; ++i) {
            int ri = roster_idx(i, off_n, garbage_time);
            float w = fmaxf(5.0f, off_usage[ri]);
            if (!garbage_time && i == off_star_idx) w *= effective_star_usage_boost;
            cumulative += w;
            bool hit = (shooter_rank < 0) && (cumulative >= pick);
            shooter_rank = hit ? i : shooter_rank;
        }
        shooter_rank = (shooter_rank < 0) ? (off_n - 1) : shooter_rank;
        int shooter = roster_idx(shooter_rank, off_n, garbage_time);

        int defender = roster_idx(shooter_rank % def_n, def_n, garbage_time);
        float on_ball_defense = def_on_ball_defense[defender];

        float shooter_fg3_pct = off_fg3_pct[shooter];
        float shooter_fg3a = off_fg3a[shooter];
        float shooter_fg_pct = off_fg_pct[shooter];
        float shooter_ft_pct = off_ft_pct[shooter];
        float shooter_usage = off_usage[shooter];
        float shooter_drive_gravity = off_drive_gravity[shooter];

        // Node 0 (Initiation): real-tendency-weighted play-type draw for how
        // this touch develops. play_type: 0 = Pick & Roll, 1 = Isolation,
        // 2 = Spot-up. See the "Decision Tree & Spacing-Driven Possession
        // Engine" comment block above kPnrPlaymakingWeight for the full
        // rationale.
        // Macro Tactical State Modifier: Shot Clock Urgency -- see the
        // comment block above kShotClockFull. A fresh touch draws against a
        // real 24s shot clock (14s after this possession's own offensive
        // rebound); under kShotClockUrgencyThreshold seconds remaining, the
        // read bypasses ball movement in the Node 0 weights below.
        float shot_clock_full = (attempt == 0) ? kShotClockFull : kShotClockOreb;
        float shot_clock_used = kShotClockMinBurn + curand_uniform(rand_state) * (shot_clock_full - kShotClockMinBurn - 0.5f);
        bool shot_clock_urgency = (shot_clock_full - shot_clock_used) < kShotClockUrgencyThreshold;

        float pnr_w = fmaxf(0.1f, off_playmaking_gravity_avg) * kPnrPlaymakingWeight;
        float iso_w = fmaxf(0.1f, shooter_usage) * kIsoUsageWeight;
        float spotup_w = fmaxf(0.1f, shooter_fg3a) * kSpotupFg3aWeight;

        // Macro DNA Layer: Team Tactical Archetype baseline bias (see the
        // comment block above kArchetypeBalanced) -- applied FIRST, to the
        // real-tendency weights, so the situational modifiers below (shot
        // clock urgency/desperation/protect lead) still compose on top of
        // this team's own baseline identity rather than overriding it
        // (e.g. a Pick & Roll Heavy team's elevated pnr_w still gets
        // correctly zeroed out by shot clock urgency -- no team runs a
        // half-court set with under 5 seconds left).
        if (off_archetype == kArchetypePaceAndSpace) {
            spotup_w *= kPaceSpaceSpotupMult;
        } else if (off_archetype == kArchetypePickAndRollHeavy) {
            pnr_w *= kPnrHeavyPnrMult;
            iso_w *= kPnrHeavyIsoMult;
        } else if (off_archetype == kArchetypePaintDominant) {
            iso_w *= kPaintDominantIsoMult;
            spotup_w *= kPaintDominantSpotupMult;
        }

        if (shot_clock_urgency) {
            pnr_w = 0.0f;  // bypass complex passing/initiation -- no time left
            iso_w *= kShotClockUrgencyTendencyMult;
            spotup_w *= kShotClockUrgencyTendencyMult;
        }
        if (desperation) {
            spotup_w *= kDesperationSpotupTendencyMult;  // trailing late -- hunt the 3
        } else if (protect_lead) {
            spotup_w *= kProtectLeadSpotupTendencyMult;  // leading late -- fewer quick 3s
            pnr_w *= kProtectLeadPnrTendencyMult;        // ...more clock-eating ball movement instead
        }
        // Game Momentum & Scoring Runs -- a team riding a real recent
        // scoring run (off_momentum_edge, see the comment block above
        // cold_streak) feeds its confident, hot-handed shot creator more:
        // a genuine "let him cook" tendency shift, layered on top of every
        // other Node 0 bias above rather than replacing any of them.
        // Mirrors main.cpp exactly.
        if (off_momentum_edge > tuning.momentum_hot_threshold) {
            iso_w *= tuning.momentum_hot_tendency_mult;
        }
        float play_pick = curand_uniform(rand_state) * (pnr_w + iso_w + spotup_w);
        int play_type = (play_pick < pnr_w) ? 0 : (play_pick < pnr_w + iso_w) ? 1 : 2;

        // Node 1 (Paint Openness Score): real floor spacing + this
        // shooter's own real drive gravity, minus the defense's real
        // rim-protection/help-IQ activity -- all relative to their existing
        // neutral baselines. A Spot-up touch leans further into the
        // offense's spacing gravity (that's the whole premise of the play);
        // a Pick & Roll/Isolation touch leans further into this player's
        // own individual drive gravity.
        float paint_openness = (off_gravity - kNeutralOffGravity) * tuning.off_gravity_openness_weight
            + (shooter_drive_gravity - kNeutralDriveGravity) * tuning.drive_gravity_openness_weight
            - (def_rim_protection_best_eff - kNeutralRimProtection) * tuning.rim_protect_suppression_weight
            - (def_help_defense_iq_avg_eff - kNeutralHelpDefenseIq) * tuning.help_iq_suppression_weight;
        if (play_type == 2) {
            paint_openness += (off_gravity - kNeutralOffGravity) * tuning.off_gravity_openness_weight * 0.5f;
        } else if (play_type == 1) {
            paint_openness += (shooter_drive_gravity - kNeutralDriveGravity) * tuning.drive_gravity_openness_weight * 0.5f;
        }
        // Macro DNA Layer: Paint Dominant teams also get a direct Paint
        // Openness Score bump (see the comment block above
        // kPaintDominantOpennessBonus) -- tilts Node 2 toward Drive &
        // Paint Finish over a jump shot, on top of Node 0's iso/spot-up
        // tendency shift above.
        if (off_archetype == kArchetypePaintDominant) {
            paint_openness += kPaintDominantOpennessBonus;
        }

        // Node 2 (Branching Resolution): Paint Openness gates a 3-way
        // branch. is_kick_out (Drive & Kick, an open catch-and-shoot 3) and
        // is_paint_finish (Drive & Paint Finish, an unhelped rim look) are
        // the two "defense got beat" outcomes; the remaining case is
        // Contested ISO/Stifle -- a Spot-up touch run down resolves as a
        // contested 3 (the shot the play called for), a Pick & Roll/
        // Isolation touch resolves as a contested drive/pull-up.
        bool is_paint_finish = false;
        bool is_kick_out = false;
        bool is_three;
        if (paint_openness >= kPaintOpenThreshold) {
            is_paint_finish = true;
            is_three = false;
        } else if (paint_openness <= kPaintLockedThreshold) {
            is_three = (play_type == 2);
        } else {
            is_kick_out = true;
            is_three = true;
        }

        // Conditional Foul & Free Throw Mechanics Engine -- see the
        // comment block above kNeutralPersonalFouls for the full
        // rationale. Three real, independent checks at this engine's two
        // documented trigger points (Drive attempts / Shot contests), each
        // anchored to already-real, already-flowing per-player data
        // instead of one flat coin flip.

        // 1) Offensive Foul / Charging -- DRIVE ATTEMPTS only (a charge is
        // a driving-lane collision, not a jump-shot contest). Conditioned
        // on the defense's own real rim-protection presence -- good
        // helpside/post defenders draw more charges. Immediate turnover,
        // no free throws.
        if (!is_three) {
            float charge_prob = kBaseChargeRate
                + kChargeRatePerRimProtection * (def_rim_protection_best_eff - kNeutralRimProtection);
            charge_prob = fminf(kMaxChargeProb, fmaxf(0.0f, charge_prob));
            if (curand_uniform(rand_state) < charge_prob) {
                return;
            }
        }

        // 2) Shooting Foul -- checked BEFORE the shot itself resolves:
        // this is what actually reduces this engine's per-possession
        // variance toward the real NBA benchmark: it REPLACES a high-
        // variance single FG attempt (a Bernoulli whose variance scales
        // with point-value^2: 9 for a 3, 4 for a 2) with a lower-variance
        // multi-FT trip (value^2=1 per throw), rather than stacking FT
        // scoring on top of an unmodified FG resolution (which would only
        // ADD variance, not trade it -- the bug in this mechanism's first
        // implementation, caught by re-measuring std dev after building it
        // and finding it hadn't moved). Conditioned on the shooter's own
        // real drive gravity (more aggressive drivers draw more contact,
        // on EITHER shot type) and the primary defender's own real
        // personal-fouls/game rate. A whistle stops play -- no oreb loop
        // on a foul.
        float shooting_foul_prob = (is_three ? kShootingFoulRateOnKickOut3 : kShootingFoulRateOnDrive)
            + kFoulRatePerDriveGravity * (shooter_drive_gravity - kNeutralDriveGravity)
            + kFoulRatePerDefFoulRate * (def_personal_fouls_rate[defender] - kNeutralPersonalFouls);
        shooting_foul_prob = fminf(kMaxShootingFoulProb, fmaxf(kMinShootingFoulProb, shooting_foul_prob));
        if (curand_uniform(rand_state) < shooting_foul_prob) {
            // Foul Trouble Tracking: this specific foul counts toward the
            // defender's OWN accumulated total only if they're this team's
            // real rim anchor.
            if (defender == def_rim_anchor_idx) ++(*def_rim_anchor_fouls);
            int num_fts = is_three ? 3 : 2;
            for (int ft = 0; ft < num_fts; ++ft) {
                if (curand_uniform(rand_state) <= shooter_ft_pct) *score += 1;
            }
            return;
        }

        // 3) Non-Shooting / Penalty Foul -- a real, SEPARATE, additive
        // foul category (an independent roll, not stealing from (2)'s
        // probability budget -- preserves this engine's already-
        // calibrated scoring average). Mirrors the real NBA bonus rule: 5
        // team fouls in a quarter sends the fouled player to the line;
        // below that, it's a dead ball and the SAME team keeps the ball
        // for another look this same possession (this loop's `continue`,
        // which the existing attempt>0 Shot Clock Urgency logic above
        // already resolves identically to an offensive-rebound
        // continuation).
        float non_shooting_foul_prob = kBaseNonShootingFoulRate
            + kNonShootingFoulRatePerDefFoulRate * (def_personal_fouls_rate[defender] - kNeutralPersonalFouls);
        non_shooting_foul_prob = fminf(kMaxNonShootingFoulProb, fmaxf(kMinNonShootingFoulProb, non_shooting_foul_prob));
        if (curand_uniform(rand_state) < non_shooting_foul_prob) {
            if (defender == def_rim_anchor_idx) ++(*def_rim_anchor_fouls);
            int fouls_now = ++(*def_team_fouls_this_q);
            if (fouls_now >= kTeamFoulsBonusThreshold) {
                for (int ft = 0; ft < kBonusFreeThrows; ++ft) {
                    if (curand_uniform(rand_state) <= shooter_ft_pct) *score += 1;
                }
                return;
            }
            continue;
        }

        bool made;
        if (is_three) {
            // Drive & Kick (open catch-and-shoot 3) or a Spot-up Contested
            // 3. Game-to-Game Stochastic Variance (off_shooting_variance)
            // scales the shooter's own real fg3_pct for this specific game
            // -- see the comment block above tuning.game_variance_std_dev.
            float made_prob = shooter_fg3_pct * off_shooting_variance
                + off_gravity * 0.006f
                + kPlaymakingMadeProbPerAssist * (off_playmaking_gravity_avg - kNeutralPlaymakingGravity)
                - kOnBallContestPerRatingPoint * (on_ball_defense - kNeutralOnBallDefense)
                - def_gravity * 0.001f
                - kFtSubstitutionProbReduction
                + shift;
            if (is_kick_out) {
                made_prob *= tuning.open_shot_bonus_multiplier;  // genuinely open look -- defense collapsed elsewhere
            } else {
                made_prob -= tuning.contested_iso_fg_pct_penalty;  // Spot-up run down -- fully contested
            }
            if (!garbage_time && shooter == off_star_idx) made_prob *= effective_hot_hand_boost;
            // Game Momentum & Scoring Runs -- a real confidence bump on a
            // hot run, folded in here so it participates in the same
            // Node 2 Probability Compression as everything else below
            // rather than bypassing it.
            if (off_momentum_edge > tuning.momentum_hot_threshold) made_prob += tuning.momentum_hot_made_prob_bonus;
            // Clutch Factor & Overtime Desperation Boost -- "shooting
            // confidence multipliers (Node 2)": a real, modest additive
            // confidence bump during clutch time, applying to WHOEVER is
            // shooting (not just the star -- that's effective_star_usage_boost's
            // job above), folded in here so it participates in the same
            // Node 2 Probability Compression as everything else. Stacks
            // with the momentum bonus above (independent triggers).
            if (clutch_time) made_prob += tuning.clutch_shooting_confidence_bonus;
            // Node 2 Probability Compression -- see the comment block
            // above tuning.final_prob_compression_scale: this is where "diminishing
            // returns" actually lives now, applied ONCE to the fully-
            // assembled made_prob (every upstream effect already folded
            // in) instead of scattered across each individual input.
            made_prob = tuning.league_avg_shot_prob + dampen(made_prob - tuning.league_avg_shot_prob, tuning.final_prob_compression_scale);
            made_prob = fminf(kMaxShotProb, fmaxf(kMinShotProb, made_prob));
            made = curand_uniform(rand_state) <= made_prob;
        } else {
            // Drive & Paint Finish (unhelped rim look) or Contested
            // ISO/Stifle (2PT). Both anchored to the shooter's own real
            // overall FG%, not a flat player-agnostic constant, scaled by
            // this game's off_shooting_variance draw.
            float made_prob = shooter_fg_pct * off_shooting_variance - kFtSubstitutionProbReduction + shift;
            if (is_paint_finish) {
                made_prob += tuning.paint_finish_fg_pct_bonus;  // defense couldn't fully commit help
            } else {
                // NOTE: def_rim_protection_best is NOT re-applied here --
                // it already drove paint_openness's gate into this branch
                // (see Node 1 above). Re-subtracting it here on top of that
                // would double-count the same real stat against this shot,
                // exactly the compounding this file's rim_protection_best/
                // help_defense_iq_avg magnitudes are deliberately kept small
                // to avoid (see the "avoiding double-counting" comment block
                // above kBaseTurnoverRate).
                made_prob -= tuning.contested_iso_fg_pct_penalty;
            }
            if (!garbage_time && shooter == off_star_idx) made_prob *= effective_hot_hand_boost;
            // Game Momentum & Scoring Runs -- see the comment block above
            // this same bonus in the 3PT branch.
            if (off_momentum_edge > tuning.momentum_hot_threshold) made_prob += tuning.momentum_hot_made_prob_bonus;
            // Clutch Factor & Overtime Desperation Boost -- "shooting
            // confidence multipliers (Node 2)": a real, modest additive
            // confidence bump during clutch time, applying to WHOEVER is
            // shooting (not just the star -- that's effective_star_usage_boost's
            // job above), folded in here so it participates in the same
            // Node 2 Probability Compression as everything else. Stacks
            // with the momentum bonus above (independent triggers).
            if (clutch_time) made_prob += tuning.clutch_shooting_confidence_bonus;
            // Node 2 Probability Compression -- see the comment block
            // above tuning.final_prob_compression_scale.
            made_prob = tuning.league_avg_shot_prob + dampen(made_prob - tuning.league_avg_shot_prob, tuning.final_prob_compression_scale);
            made_prob = fminf(kMaxShotProb, fmaxf(kMinShotProb, made_prob));
            made = curand_uniform(rand_state) <= made_prob;
        }

        if (made) {
            *score += is_three ? 3 : 2;
            // And-1: a made shot also draws a shooting foul at a real,
            // published rate. Undefended FT -- no `shift` applied. A small,
            // genuinely additive bonus (not a substitution) -- real and-1s
            // are bonus scoring on top of an already-made shot.
            if (curand_uniform(rand_state) < kAndOneRateOnMake) {
                if (curand_uniform(rand_state) <= shooter_ft_pct) *score += 1;
            }
            return;
        }

        // Missed, no foul on this attempt -- Offensive Rebound check (real
        // data: the offense's best real rebounder vs. the defense's real
        // team-wide rebounding activity). No attempts left, or the defense
        // secures it: possession over, no points.
        bool attempts_remaining = attempt < kMaxPossessionAttempts - 1;
        if (!attempts_remaining) return;

        float oreb_prob = kBaseOffRebRate
            + kOrebPerRealOreb * (off_reb_gravity_best - kNeutralOffRebGravity)
            - kOrebSuppressionPerRealDreb * (def_reb_gravity_avg - kNeutralDefRebGravity);
        oreb_prob = fminf(kMaxOrebProb, fmaxf(kMinOrebProb, oreb_prob));
        if (curand_uniform(rand_state) >= oreb_prob) {
            return;  // defensive rebound -- possession over
        }
        // else: offensive rebound secured -- loop back for another look.
    }
}

// One thread per Monte Carlo trial (one full simulated game). Each thread
// alternates possessions between the two offenses, drawing from one shared
// 48-minute game clock (see the "Shared Game Clock" comment block above)
// until it expires, accumulating final scores independently -- no
// cross-thread communication, no console I/O. Threads now run a
// data-dependent number of loop iterations (the shared clock's randomly
// drawn possession lengths), which is inherent to modeling a real,
// variable-length shared resource -- some extra warp divergence versus the
// old fixed-iteration-count loop is an accepted, necessary tradeoff, not an
// oversight.
__global__ void monte_carlo_matchup_kernel(const float* a_fg3_pct, const float* a_fg3a, const float* a_fg_pct, const float* a_ft_pct,
                                            const float* a_drive_gravity,
                                            const float* a_usage, const float* a_position_weight,
                                            const float* a_on_ball_defense, const float* a_personal_fouls, int num_a,
                                            int star_idx_a, float a_help_defense_iq, float a_rim_protection,
                                            float a_playmaking_gravity, float a_off_reb_gravity, float a_def_reb_gravity,
                                            float a_help_defense_iq_bench, float a_rim_protection_bench,
                                            float a_playmaking_gravity_bench, float a_off_reb_gravity_bench, float a_def_reb_gravity_bench,
                                            const float* b_fg3_pct, const float* b_fg3a, const float* b_fg_pct, const float* b_ft_pct,
                                            const float* b_drive_gravity,
                                            const float* b_usage, const float* b_position_weight,
                                            const float* b_on_ball_defense, const float* b_personal_fouls, int num_b,
                                            int star_idx_b, float b_help_defense_iq, float b_rim_protection,
                                            float b_playmaking_gravity, float b_off_reb_gravity, float b_def_reb_gravity,
                                            float b_help_defense_iq_bench, float b_rim_protection_bench,
                                            float b_playmaking_gravity_bench, float b_off_reb_gravity_bench, float b_def_reb_gravity_bench,
                                            int num_simulations,
                                            float combined_prob_shift, float hot_hand_boost,
                                            float fatigue_prob_penalty_a, float fatigue_gravity_mult_a,
                                            float fatigue_prob_penalty_b, float fatigue_gravity_mult_b,
                                            int archetype_a, int archetype_b,
                                            int rim_anchor_idx_a, int rim_anchor_idx_b,
                                            EngineTuningParams tuning,
                                            int* out_score_a, int* out_score_b) {
    int idx = blockIdx.x * blockDim.x + threadIdx.x;
    if (idx >= num_simulations) return;

    curandState rand_state;
    curand_init(19932026ULL, idx, 0, &rand_state);

    // Game-to-Game Stochastic Variance (see the comment block above
    // tuning.game_variance_std_dev) -- drawn ONCE per team per thread (i.e. once per
    // simulated game), before the per-thread while loop, and held fixed for
    // every possession that follows. Mirrors main.cpp's identical
    // per-game draw exactly.
    const float game_off_variance_a = fminf(tuning.game_variance_max, fmaxf(tuning.game_variance_min, 1.0f + curand_normal(&rand_state) * tuning.game_variance_std_dev));
    const float game_def_variance_a = fminf(tuning.game_variance_max, fmaxf(tuning.game_variance_min, 1.0f + curand_normal(&rand_state) * tuning.game_variance_std_dev));
    const float game_off_variance_b = fminf(tuning.game_variance_max, fmaxf(tuning.game_variance_min, 1.0f + curand_normal(&rand_state) * tuning.game_variance_std_dev));
    const float game_def_variance_b = fminf(tuning.game_variance_max, fmaxf(tuning.game_variance_min, 1.0f + curand_normal(&rand_state) * tuning.game_variance_std_dev));

    int score_a = 0;
    int score_b = 0;

    // Team Fouls / Bonus (Conditional Foul & Free Throw Mechanics Engine)
    // -- real, per-quarter team-foul counters, reset whenever
    // total_game_seconds crosses into a new real 720s (12-minute) quarter.
    // Mirrors main.cpp's identical quarter-boundary check exactly.
    int team_a_fouls_this_q = 0;
    int team_b_fouls_this_q = 0;
    int last_foul_reset_quarter = 1;

    // Foul Trouble Tracking -- each team's real rim anchor's (rim_anchor_idx_a/b)
    // live foul count, accumulating for the WHOLE game (unlike the per-
    // quarter team counters above -- a real player's foul trouble doesn't
    // reset at the quarter break). Mirrors main.cpp exactly.
    int a_rim_anchor_fouls = 0;
    int b_rim_anchor_fouls = 0;

    // Game Momentum & Scoring Runs -- an exponentially-decayed recent-
    // scoring accumulator per team (see the comment block above
    // cold_streak in simulate_possession), updated after every possession
    // below. 0.0 at tip-off -- a fresh game has no momentum yet. Mirrors
    // main.cpp exactly.
    float momentum_a = 0.0f;
    float momentum_b = 0.0f;

    int total_game_seconds = 0;
    // Overtime (OT) -- see the comment block above compute_period(). Real
    // NBA rule: a tied score at the end of a period (regulation OR a prior
    // OT) forces another full OT period; game_end_seconds is extended by
    // tuning.ot_period_seconds each time this happens, and the SAME
    // per-round possession logic below just keeps running against that new
    // boundary -- every other piece of live per-thread state (momentum,
    // team-foul-bonus tracking, the rim anchors' own foul counts) carries
    // over automatically. ot_periods_played is capped by
    // tuning.max_ot_periods purely as a safety net against a pathological
    // infinite tie streak. Mirrors main.cpp's run_48min_simulation exactly.
    int game_end_seconds = kGameDurationSeconds;
    int ot_periods_played = 0;
    while (true) {
        if (total_game_seconds >= game_end_seconds) {
            if (score_a != score_b || ot_periods_played >= tuning.max_ot_periods) break;
            ++ot_periods_played;
            game_end_seconds += tuning.ot_period_seconds;
        }
        // Garbage Time: real, symmetric, deterministic -- see the comment
        // block above kGarbageTimeMarginThreshold. Computed once per round
        // (both this round's A and B calls see the same value) exactly like
        // the old possession-index version did, just keyed off the shared
        // clock instead of a fixed per-team possession counter.
        bool garbage_time = (total_game_seconds >= kGarbageTimeStartSeconds) &&
            (abs(score_a - score_b) >= kGarbageTimeMarginThreshold);

        int quarter_now = compute_period(total_game_seconds, tuning.ot_period_seconds);
        if (quarter_now != last_foul_reset_quarter) {
            team_a_fouls_this_q = 0;
            team_b_fouls_this_q = 0;
            last_foul_reset_quarter = quarter_now;
        }

        // Foul-Out (real NBA 6-personal-foul rule): once a team's real rim
        // anchor -- the ONE individually-tracked player identity this GPU
        // engine models (see the comment block above GPURoster::rim_anchor_idx)
        // -- crosses tuning.foul_out_threshold, they're done for the rest of
        // the game. This engine has no per-thread substitution model to
        // literally bench them (see monte_carlo_matchup_kernel's own
        // comment block for why that's a deliberate, documented CPU/GPU
        // asymmetry, not an oversight), so it reuses the SAME starter/bench
        // aggregate swap garbage_time already relies on: the team's real
        // BENCH rim-protection figure stands in for "backup center is in"
        // for the rest of the game, exactly like a real coach's next move.
        bool b_anchor_fouled_out = (b_rim_anchor_fouls >= tuning.foul_out_threshold);
        bool a_anchor_fouled_out = (a_rim_anchor_fouls >= tuning.foul_out_threshold);

        float eff_b_help_iq = garbage_time ? b_help_defense_iq_bench : b_help_defense_iq;
        float eff_b_rim = (garbage_time || b_anchor_fouled_out) ? b_rim_protection_bench : b_rim_protection;
        float eff_a_playmaking = garbage_time ? a_playmaking_gravity_bench : a_playmaking_gravity;
        float eff_a_off_reb = garbage_time ? a_off_reb_gravity_bench : a_off_reb_gravity;
        float eff_b_def_reb = garbage_time ? b_def_reb_gravity_bench : b_def_reb_gravity;
        // Game Momentum & Scoring Runs -- decay both teams' momentum once
        // per possession (see the comment block above cold_streak in
        // simulate_possession), then feed team A's OWN edge over B into
        // A's upcoming possession, and update A's accumulator afterward
        // from the real points it just scored. Mirrors main.cpp exactly.
        momentum_a *= tuning.momentum_decay;
        momentum_b *= tuning.momentum_decay;
        int score_a_before_poss = score_a;
        simulate_possession(a_fg3_pct, a_fg3a, a_fg_pct, a_ft_pct, a_drive_gravity, a_usage, a_position_weight, num_a, star_idx_a,
                             b_fg3_pct, b_fg3a, b_position_weight, b_on_ball_defense, b_personal_fouls, num_b,
                             eff_b_help_iq, eff_b_rim, eff_a_playmaking,
                             eff_a_off_reb, eff_b_def_reb,
                             combined_prob_shift, hot_hand_boost, garbage_time,
                             fatigue_prob_penalty_a, fatigue_gravity_mult_a, score_b - score_a,
                             archetype_a, game_off_variance_a, game_def_variance_b,
                             momentum_a - momentum_b, rim_anchor_idx_b, &b_rim_anchor_fouls,
                             &team_b_fouls_this_q, tuning, game_end_seconds,
                             &total_game_seconds, &rand_state, &score_a);
        momentum_a += static_cast<float>(score_a - score_a_before_poss);
        if (total_game_seconds >= game_end_seconds) continue;

        float eff_a_help_iq = garbage_time ? a_help_defense_iq_bench : a_help_defense_iq;
        float eff_a_rim = (garbage_time || a_anchor_fouled_out) ? a_rim_protection_bench : a_rim_protection;
        float eff_b_playmaking = garbage_time ? b_playmaking_gravity_bench : b_playmaking_gravity;
        float eff_b_off_reb = garbage_time ? b_off_reb_gravity_bench : b_off_reb_gravity;
        float eff_a_def_reb = garbage_time ? a_def_reb_gravity_bench : a_def_reb_gravity;
        momentum_a *= tuning.momentum_decay;
        momentum_b *= tuning.momentum_decay;
        int score_b_before_poss = score_b;
        simulate_possession(b_fg3_pct, b_fg3a, b_fg_pct, b_ft_pct, b_drive_gravity, b_usage, b_position_weight, num_b, star_idx_b,
                             a_fg3_pct, a_fg3a, a_position_weight, a_on_ball_defense, a_personal_fouls, num_a,
                             eff_a_help_iq, eff_a_rim, eff_b_playmaking,
                             eff_b_off_reb, eff_a_def_reb,
                             -combined_prob_shift, hot_hand_boost, garbage_time,
                             fatigue_prob_penalty_b, fatigue_gravity_mult_b, score_a - score_b,
                             archetype_b, game_off_variance_b, game_def_variance_a,
                             momentum_b - momentum_a, rim_anchor_idx_a, &a_rim_anchor_fouls,
                             &team_a_fouls_this_q, tuning, game_end_seconds,
                             &total_game_seconds, &rand_state, &score_b);
        momentum_b += static_cast<float>(score_b - score_b_before_poss);
    }

    out_score_a[idx] = score_a;
    out_score_b[idx] = score_b;
}

struct BatchStats {
    int team_a_wins = 0;
    int team_b_wins = 0;
    int ties = 0;
    double avg_score_a = 0.0;
    double avg_score_b = 0.0;
    double avg_margin = 0.0;
    double margin_stddev = 0.0;
};

BatchStats aggregate_results(const std::vector<int>& scores_a, const std::vector<int>& scores_b) {
    BatchStats stats;
    const int n = static_cast<int>(scores_a.size());

    double sum_a = 0.0;
    double sum_b = 0.0;
    std::vector<int> margins(n);

    for (int i = 0; i < n; ++i) {
        sum_a += scores_a[i];
        sum_b += scores_b[i];
        margins[i] = scores_a[i] - scores_b[i];

        if (scores_a[i] > scores_b[i]) {
            ++stats.team_a_wins;
        } else if (scores_b[i] > scores_a[i]) {
            ++stats.team_b_wins;
        } else {
            ++stats.ties;
        }
    }

    stats.avg_score_a = sum_a / n;
    stats.avg_score_b = sum_b / n;

    double sum_margin = 0.0;
    for (int m : margins) sum_margin += m;
    stats.avg_margin = sum_margin / n;

    double sq_diff_sum = 0.0;
    for (int m : margins) {
        double diff = m - stats.avg_margin;
        sq_diff_sum += diff * diff;
    }
    stats.margin_stddev = std::sqrt(sq_diff_sum / n);

    return stats;
}

// Index of the roster's highest usage_rate entry -- the "star" the hot-hand
// boost applies to. A plain host-side scan since it only needs to run once
// per team per batch (not once per thread), unlike the possession loop.
int argmax_usage(const std::vector<float>& usage_rate) {
    int best_idx = 0;
    for (size_t i = 1; i < usage_rate.size(); ++i) {
        if (usage_rate[i] > usage_rate[best_idx]) best_idx = static_cast<int>(i);
    }
    return best_idx;
}

// Team Tactical Archetypes (Macro DNA Layer) -- see the comment block above
// kArchetypeBalanced. Dynamically derives a team's primary offensive
// identity from three already-real, already-flowing per-team aggregates
// (no fabricated data): mean 3PT-attempt volume and mean real
// free-throw-attempt "drive" rate across the top-5 (by minutes) rotation
// (mirrors playmaking_gravity_avg's own "top-5 rotation mean" convention
// in cuda_main.cpp::build_gpu_roster), plus playmaking_gravity_avg itself
// (already precomputed on GPURoster). Each is compared to its own
// already-established neutral baseline as a relative deviation, and the
// largest POSITIVE deviation that clears kArchetypeDeviationThreshold wins;
// a team that isn't meaningfully above neutral on any axis is Balanced --
// a real, honest "no strong identity" outcome, not a forced label. A plain
// host-side scan (runs once per team per batch, before the kernel launch),
// operating on GPURoster's own host-side std::vector fields, same
// convention as argmax_usage above. Mirrors main.cpp's
// derive_team_archetype() exactly (same inputs, same thresholds), so a
// real roster gets the same archetype label on both the CPU narrative
// engine and the GPU Monte Carlo batch.
int derive_team_archetype(const GPURoster& team) {
    size_t on_court_n = std::min(static_cast<size_t>(5), team.fg3a.size());
    if (on_court_n == 0) return kArchetypeBalanced;

    double fg3a_sum = 0.0;
    double drive_sum = 0.0;
    for (size_t i = 0; i < on_court_n; ++i) {
        fg3a_sum += team.fg3a[i];
        drive_sum += (i < team.drive_gravity.size()) ? team.drive_gravity[i] : kNeutralDriveGravity;
    }
    double fg3a_avg = fg3a_sum / static_cast<double>(on_court_n);
    double drive_avg = drive_sum / static_cast<double>(on_court_n);

    double space_dev = (fg3a_avg - kNeutralTeamFg3aAvg) / kNeutralTeamFg3aAvg;
    double pnr_dev = (team.playmaking_gravity_avg - kNeutralPlaymakingGravity) / kNeutralPlaymakingGravity;
    double paint_dev = (drive_avg - kNeutralDriveGravity) / kNeutralDriveGravity;

    double best_dev = static_cast<double>(kArchetypeDeviationThreshold);
    int archetype = kArchetypeBalanced;
    if (space_dev > best_dev) { best_dev = space_dev; archetype = kArchetypePaceAndSpace; }
    if (pnr_dev > best_dev) { best_dev = pnr_dev; archetype = kArchetypePickAndRollHeavy; }
    if (paint_dev > best_dev) { best_dev = paint_dev; archetype = kArchetypePaintDominant; }
    return archetype;
}

// Human-readable label for a kArchetype* value -- used only for the batch
// summary header below (has zero effect on the simulation itself). Mirrors
// main.cpp's archetype_label() exactly.
const char* archetype_label(int archetype) {
    switch (archetype) {
        case kArchetypePaceAndSpace: return "Pace & Space / 5-Out";
        case kArchetypePickAndRollHeavy: return "Pick & Roll Heavy";
        case kArchetypePaintDominant: return "Paint Dominant / Post-Up";
        default: return "Balanced";
    }
}

