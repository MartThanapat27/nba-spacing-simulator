// Converts an external ML-predicted point-margin bias (GPUMatchupInput::ml_margin_bias,
// e.g. from train_ml_model.py) into a per-possession shot-probability shift.
//
// Derivation: a made shot is worth ~kAvgPointsPerMake points on average (a blend of
// 2PT/3PT makes), so nudging one team's make probability by `delta_p` on every
// possession shifts that team's expected points by roughly
// `delta_p * kAvgPointsPerMake * kPossessionsPerTeam`. Applying +delta_p to Team A's
// shots and -delta_p to Team B's doubles that swing in the margin, so:
//   margin_bias ~= 2 * delta_p * kAvgPointsPerMake * kPossessionsPerTeam
//   delta_p      = margin_bias / (2 * kAvgPointsPerMake * kPossessionsPerTeam)
// This is a simple linear calibration, not a fitted transform -- consistent with the
// rest of this kernel's "simplified, high-performance" possession model.
constexpr float kAvgPointsPerMake = 2.3f;
constexpr float kMlMarginToProbShift = 1.0f / (2.0f * kAvgPointsPerMake * static_cast<float>(kPossessionsPerTeam));

// Home Court Advantage override -- calibrated_constants.h's
// kHomeCourtProbShift is the honest OLS-fitted value (~0.80 points
// equivalent, statistically insignificant at n=120 -- see that header's
// regression report), which this task's explicit calibration goal
// supersedes with a modern, commonly-cited real regular-season home-court
// point value instead (recent NBA seasons run closer to 2-2.5 points,
// well down from the ~3-point "textbook" era value calibrated_constants.h
// deliberately avoided hard-coding). A hand-set literal, not independently
// regression-fit -- same honesty convention as this engine's other
// qualitative design constants, and kept in sync with
// backend/api_simulation.py's kHomeCourtPointsPrior (also 2.25) so the raw
// engine and the market-prior safety brake agree on this one real-world
// number. Mirrors main.cpp exactly.
constexpr float kHomeCourtPointsOverride = 2.25f;
constexpr float kHomeCourtProbShiftOverride = kHomeCourtPointsOverride * kMlMarginToProbShift;

