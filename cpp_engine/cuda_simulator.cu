// (see kPnrPlaymakingWeight below) -- ball movement is what a Pick & Roll
// touch actually represents.
constexpr float kPlaymakingMadeProbPerAssist = 0.003f;

// Kick-out to Open 3PT: uses the shooter's real fg3_pct directly (an "open"
// look should convert close to a shooter's true percentage), lightly
// contested by the primary defender's on-ball defense rating.
constexpr float kOnBallContestPerRatingPoint = 0.0006f;

