constexpr float kMinShotProb = 0.20f;
constexpr float kMaxShotProb = 0.75f;

// ---------------------------------------------------------------------------
// Node 2 Probability Compression (Diminishing Returns)
//
// Node 1's Paint Openness Score stays linear -- it already resolves into a
// discrete, non-linear 3-way branch CHOICE (Drive & Paint Finish / Drive &
// Kick / Contested ISO) via a threshold gate, not a smoothly-compounding
// probability, so dampening its inputs individually (a first version of
// this mechanism did exactly that) doesn't touch where the real problem
// lives, and interacts unpredictably with Game-to-Game Stochastic Variance
// below (a Jensen's-inequality-style bias was measured: dampening a stat
// BEFORE multiplying it by a symmetric per-game variance draw shifts its
// EXPECTED value, not just its variance). Node 2's fully-assembled
// made_prob, right before the safety clamp, is instead the ONE place every
// upstream effect (Node 0/1's branch choice, the shooter's real
// fg_pct/fg3_pct scaled by this game's variance draw, the def-rating/
// home-court/fatigue/ML-margin `shift`, archetype and situational-modifier
// bonuses) has already been combined into a single number -- compressing
// THAT directly prevents any COMBINATION of them from snowballing into an
// extreme per-shot probability, without picking which individual upstream
// input to distrust:
//   made_prob = tuning.league_avg_shot_prob + dampen(made_prob - tuning.league_avg_shot_prob, tuning.final_prob_compression_scale)
// dampen(gap, scale) = scale * tanh(gap / scale): for |gap| << scale this
// is indistinguishable from an unmodified made_prob (tanh(x) ~= x for
// small x), so an ordinary shot's probability is barely touched; for
// |gap| >> scale it saturates instead of growing without bound. Mirrors
// main.cpp's identically-named function/constants exactly.
//
// Cumulative Probability Bias investigation (why a MODEST real gap can
// still separate further than a well-calibrated market-style prior would):
// traced Node 0 (Initiation)/Node 1 (Paint Openness)/Node 2 (this
// compression) across a full possession loop against a controlled test (two
// IDENTICAL rosters, differing ONLY in GPURoster::def_rating by a real,
// modest gap) to isolate the effect from any confounding real per-player
// stat differences. Node 0/1 are NOT the source: Node 0 is a categorical
// play-type draw (no probability to compound), and Node 1's Paint Openness
// Score gates a discrete 3-way BRANCH CHOICE, not a smoothly-compounding
// probability (see the comment block above this Node 2 section). The
// actual mechanism is exactly what kDefResistanceProbPerRating's own
// derivation already documents: a small, honestly-fitted per-shot
// probability shift (~0.005 shot-probability per real def-rating point),
// applied identically to every one of a game's ~100 team possessions,
// compounds via the Central Limit Theorem into a LARGER aggregate win-
// probability separation than a single-number market-style prior
// (normal_cdf(margin / kRealMarginStdDev)) would project for the same real
// gap -- e.g. a controlled, isolated ~4-point real DEF_RATING gap measured
// ~62/38 raw here (a compute_market_prior()-equivalent projection for the
// same gap is ~63/37 -- i.e. the two were ALREADY closely aligned, not
// wildly divergent) yet still landed just outside a genuinely-close
// matchup's target ~40-60% band. This is a real, structural property of
// simulating ~100 possessions as (mostly) independent draws, not a
// snowballing bug in any single node -- so the fix is NOT to shrink the
// fitted kDefResistanceProbPerRating coefficient (that would misrepresent
// real calibrated data) but to retune the two REAL, already-existing
// dampening levers this section and the variance block below already
// declared for exactly this purpose: tuning.final_prob_compression_scale
// (0.16f -> 0.12f) and tuning.game_variance_std_dev (0.06f -> 0.09f, still
// within its own documented real ~8-10% range). Verified empirically: this
// pulls the isolated ~4-point-gap case from 62/38 to ~60/40 (inside the
// target band) while a genuine large real gap (~15 points) still shows
// strong, appropriately confident differentiation (~83/17, not flattened
// toward 50/50).
//
// A separate, larger contributor to any specific "close-net-rating-but-
// lopsided-raw-output" observation is a DATA CONSISTENCY issue, not a
// decision-tree defect -- see main.cpp's identical comment block for the
// full explanation (backend/main.py's player/team-defense data can be a
// season behind backend/api_simulation.py's now-dynamic market-prior
// NET_RATING fetch); that is a data-freshness concern, not something a
// possession-loop rebalance can or should paper over.
__device__ __forceinline__ float dampen(float gap, float scale) {
    return scale * tanhf(gap / scale);
}

// tuning.league_avg_shot_prob (the compression's center -- a real, roughly
// league-average made-shot probability blend) and
// tuning.final_prob_compression_scale (chosen so a made_prob within the
// existing kMinShotProb/kMaxShotProb safety band barely saturates for an
// ordinary shot, but one several stacked effects pushed well past that
// band gets meaningfully pulled back before the final clamp) are declared
// on EngineTuningParams (cuda_simulator.cuh) -- see that struct's comment
// block. `tuning` is threaded through simulate_possession as a
// pass-by-value parameter (see monte_carlo_matchup_kernel), not a global,
// since it's genuinely per-batch, ML/optimization-tunable input.

// Game-to-Game Stochastic Variance -- REAL teams have hot/cold shooting and
// engaged/sluggish defensive nights; a possession-level Monte Carlo model
// that only samples PER-SHOT randomness around a fixed, deterministic
// season-average baseline under-represents this, which is part of why the
// raw engine's win probabilities ran hotter than real single-game NBA
// upset rates (a team's TRUE per-shot edge is real, but it doesn't hold
// perfectly constant for all 100 possessions of one specific game the way
// a fixed baseline implies). Drawn ONCE per team per GAME (i.e. once per
// CUDA thread, not re-sampled per possession, which would just add
// symmetric per-shot noise the law of large numbers already washes out
// over ~100 shots) -- see monte_carlo_matchup_kernel, where these are
// sampled before the per-thread while loop and held fixed for the whole
// game. Anchored to real, commonly-documented team-level game-to-game
// shooting-efficiency variance (~8-10% relative), not independently
// regression-fit. Clamped to a plausible real single-game range -- a
// "career night" or a "no-show", not a statistical outlier.
// tuning.game_variance_std_dev/min/max are declared on EngineTuningParams.
// Mirrors main.cpp exactly.

// ---------------------------------------------------------------------------
// Decision Tree & Spacing-Driven Possession Engine
//
// REPLACES the old "independent is_three coin-flip, then an independent
// blow-by-vs-rim-contest roll" shot-selection with shot LOCATION/QUALITY as
// an EMERGENT consequence of real spacing data, resolved as three explicit
// nodes per attempt:
//
//   Node 0 (Initiation): once the usage-weighted matchup draw above has
//   already picked this attempt's ball-handler (unchanged), a real-
//   tendency-weighted categorical draw picks how THIS touch develops --
//   Pick & Roll (weighted by the offense's real playmaking_gravity_avg,
//   i.e. ball movement), Isolation (weighted by the shooter's own real
//   usage_rate), or Spot-up (weighted by the shooter's own real fg3a
//   volume). Not independently regression-fit -- a qualitative real-
//   tendency weighting, same honesty convention as this file's other
//   possession-state-machine constants.
//
//   Node 1 (Paint Openness Score): off_gravity (the existing Box-Cox 3PT
//   floor-spacing sample -- real shooters on the floor forcing defenders to
//   stay home) plus the shooter's own real drive_gravity (FTA/game -- how
//   often THIS player collapses a defense off the dribble), minus the
//   defense's real rim-protection/help-IQ aggregates (a good helpside
//   defense can afford to sag off a non-shooter without surrendering the
//   rim). All terms relative to their existing neutral baselines
//   (kNeutralRimProtection/kNeutralHelpDefenseIq, already used elsewhere in
//   this file), so this reuses already-anchored real-data scales rather
//   than inventing a new one.
//
//   Node 2 (Branching Resolution): Paint Openness gates a 3-way branch --
//   Drive & Paint Finish (openness high: attack the rim, the shooter's real
//   FG% with only a small bonus since the defense couldn't fully commit
//   help), Drive & Kick (openness middling: the defense sagged off THIS
//   player specifically, which frees a real teammate for a catch-and-shoot
//   3 -- explicit open-shot bonus multiplier on the shooter's real fg3_pct),
//   or Contested ISO / Stifle (openness low: the defense has both the
//   driving and passing lanes covered -- worst-case shot, no bonus; resolves
//   as a contested pull-up/drive for a Pick & Roll or Isolation touch, or a
//   contested catch-and-shoot 3 for a Spot-up touch that got run down).
//
// The shooting-foul-before-shot-resolution check (see kShootingFoulRateOnDrive
// below) now also branches: real shooting fouls happen disproportionately on
// drives/paint touches and are comparatively rare on catch-and-shoot 3s, so
// Drive & Kick and a Spot-up Contested attempt use the separate, lower
// kShootingFoulRateOnKickOut3 instead.
constexpr float kPnrPlaymakingWeight = 1.0f;   // real playmaking_gravity_avg -- Pick & Roll frequency proxy
constexpr float kIsoUsageWeight = 1.0f;        // real shooter usage_rate -- Isolation frequency proxy
constexpr float kSpotupFg3aWeight = 2.0f;      // real shooter fg3a -- Spot-up frequency proxy (volume shooters run more of these)

