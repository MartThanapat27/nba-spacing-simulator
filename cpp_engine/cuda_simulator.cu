// ---------------------------------------------------------------------------
// Shared Game Clock (Single-Ball Possession Engine)
//
// Mirrors main.cpp's PossessionEngine exactly (same constants, same
// mechanism): both teams draw possessions from ONE shared 48-minute clock
// (kGameDurationSeconds) instead of each independently being guaranteed a
// fixed kPossessionsPerTeam possessions no matter what the other team does.
// Each possession consumes a real, variable slice of that shared clock
// (kMinPossessionSeconds-kMaxPossessionSeconds, uniform -- covers the whole
// trip including any put-back attempts, not each individual shot), and the
// two teams strictly alternate one real possession at a time (each
// simulate_possession call already resolves a team's ENTIRE trip -- score,
// turnover, or a defensive rebound all hand the ball to the other team;
// only an offensive rebound keeps it, which the attempt-loop below already
// handles internally without exiting) -- so alternating this way already IS
// correct single-ball semantics, not an approximation of it. The resulting
// possession count per team is now an emergent property of the shared
// clock (varies possession-to-possession and game-to-game) instead of a
// hardcoded constant, which is what actually ties the two teams' scoring
// opportunities together as one shared resource.
constexpr int kGameDurationSeconds = 2880;   // 48 minutes -- REGULATION length; see kNumRegulationQuarters below for Overtime
constexpr int kRegulationQuarterSeconds = 720;
constexpr int kNumRegulationQuarters = 4;

// Overtime (OT) -- Game/Period Clock Helpers. total_game_seconds is the
// same single, monotonically increasing shared clock described above,
// except monte_carlo_matchup_kernel no longer stops it at kGameDurationSeconds:
// it extends it by tuning.ot_period_seconds (a real 5-minute NBA overtime
// period) for every additional period needed to break a tie, exactly like
// main.cpp's run_48min_simulation. These three device helpers replace the
// old fixed `/ 720` regulation-quarter arithmetic so a possession's
// clutch/team-foul-bonus logic stays correct once total_game_seconds
// exceeds kGameDurationSeconds. Mirrors main.cpp's identically-named
// functions exactly (this file just threads tuning.ot_period_seconds
// through explicitly, since there's no GPU-side global to read it from).
__device__ __forceinline__ int compute_period(int total_game_seconds, int ot_period_seconds) {
    // <= (not <): the possession landing EXACTLY on the regulation buzzer
    // is still Q4's final tick, not OT1's opening tip -- mirrors main.cpp's
    // identical boundary convention exactly.
    if (total_game_seconds <= kGameDurationSeconds) {
        return min(kNumRegulationQuarters, total_game_seconds / kRegulationQuarterSeconds + 1);
    }
    return kNumRegulationQuarters + 1 + (total_game_seconds - kGameDurationSeconds - 1) / max(1, ot_period_seconds);
}

__device__ __forceinline__ int period_start_seconds(int period, int ot_period_seconds) {
    if (period <= kNumRegulationQuarters) return (period - 1) * kRegulationQuarterSeconds;
    return kGameDurationSeconds + (period - kNumRegulationQuarters - 1) * ot_period_seconds;
}

__device__ __forceinline__ int period_length_seconds(int period, int ot_period_seconds) {
    return period <= kNumRegulationQuarters ? kRegulationQuarterSeconds : ot_period_seconds;
}

