// ---------------------------------------------------------------------------
// Free Throw / And-1 Resolution
//
// Root cause of this engine's excess per-game variance (measured: ~18.5
// point margin std dev vs. real NBA's ~12-13): every scored possession was a
// lumpy +2/+3 jump with no free-throw scoring at all. Real NBA scoring is
// ~20-23% free throws -- low-value (1 pt), low-variance (undefended, real
// ~75-78% league rate), from and-1s and shooting fouls. A Bernoulli trial's
// variance contribution scales with value^2 (9 for a made 3, 4 for a made
// 2, 1 for a made FT), so real basketball's FT mix is *structurally*
// lower-variance than an FG-only model.
//
// kShootingFoulRateOnDrive is checked BEFORE the shot resolves (not after a
// miss): this is what actually reduces variance -- it REPLACES a real
// fraction of high-variance single FG attempts with a lower-variance
// multi-FT trip, a genuine substitution of the variance SOURCE, not FT
// scoring stacked on top of an unmodified FG resolution (a first version of
// this mechanism did exactly that, added no real variance reduction, and
// was caught by re-measuring std dev after building it). kAndOneRateOnMake
// stays a pure additive bonus on a make (real and-1s don't replace
// anything). Both rates are anchored to published real and-1/shooting-foul-
// rate ranges, not independently regression-fit (same honesty convention as
// this file's other possession-state-machine constants);
// kFtSubstitutionProbReduction trims the remaining FG made_prob so the
// combined mean stays close to the pre-FT-modeling baseline -- report the
// engine's actual resulting std dev after tuning, don't force it further
// toward 12-13 with a less-principled knob if this doesn't fully close the
// gap. FT resolution deliberately does NOT apply `shift` (ml_prob_bias/
// def-resistance/home-court/fatigue) -- free throws are shot undefended
// from a fixed line, so the calibrated margin-shift term is both physically
// wrong there and would double-apply calibrated_constants.h's shift twice
// in one possession.
constexpr float kNeutralFtPct = 0.77f;               // real league-average FT%; GPURoster::ft_pct's fallback
constexpr float kAndOneRateOnMake = 0.04f;           // real and-1 rate on a made shot
constexpr float kShootingFoulRateOnDrive = 0.12f;    // real shooting-foul rate, checked before shot resolution
// Trimmed from 0.02f -- see the Scoring Calibration comment above
// tuning.contested_iso_fg_pct_penalty; this term applies to effectively every shot
// resolution, so it was a major contributor to the ~74-90-point scoring
// suppression bug. Mirrors main.cpp exactly.
constexpr float kFtSubstitutionProbReduction = 0.005f;  // trimmed from base made_prob to offset the foul-trip's higher per-attempt EV

