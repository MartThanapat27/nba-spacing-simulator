// Possession-by-Possession Probabilistic State Machine
//
// Replaces the old single shot-probability formula with a discrete decision
// tree per possession: Turnover/Bad Shot -> Shot Selection (catch-and-shoot
// "kick-out" 3 vs. isolation/drive) -> for a drive, Blow-by (beat the
// primary defender) vs. Rim-Protection-Contested (helpside rim deterrence)
// -> make/miss. This models real tactical interactions -- a minutes/usage
// -matched primary-defender matchup, help-side rim protection, on-ball
// defense, forced turnovers -- instead of one flattened shooting formula.
//
// Every player-level and team-level input here is a REAL stat already
// flowing through /api/players (fg3_pct, fg3a, usage_rate for offense; real
// season blocks/game and steals/game -- see GPURoster::rim_protection_best /
// help_defense_iq_avg -- for team-wide defense), never a fabricated number.
// GPURoster::on_ball_defense_rating (the one genuinely new per-player input)
// has no real, freely-available tracking-stat source wired into this
// project yet (that would need nba_api's leaguedashptdefend), so it stays
// at its documented neutral default (50.0) until that data is integrated --
// see cuda_main.cpp::build_gpu_roster.
//
// The per-event PROBABILITY MAGNITUDES below (kBaseTurnoverRate,
// kBaseBlowByRate, kContestedRimMadeProb, etc.) are NOT independently
// regression-fit against this project's own possession-level outcome data
// the way kDefResistanceProbPerRating was (that would need real
// shot-location/play-type tracking data this project doesn't have) --
// they're anchored to well-documented, published real-world NBA benchmarks
// (a league-average possession-level turnover rate of roughly 13%, and a
// well-documented ~5-10 percentage point gap between contested and
// uncontested rim FG% against elite shot blockers) and clamped to sane
// ranges, consistent with this file's existing kFatigueGravityMultiplier
// precedent: an honest, real-benchmark-anchored design constant, not a
// statistically proven coefficient. Re-anchor against real possession
// outcome data if/when it becomes available.
constexpr float kNeutralOnBallDefense = 50.0f;   // 0-100 scale; GPURoster::on_ball_defense_rating's neutral default
constexpr float kNeutralHelpDefenseIq = 1.0f;    // real steals/game baseline; GPURoster::help_defense_iq_avg's neutral default
constexpr float kNeutralRimProtection = 0.5f;    // real blocks/game baseline; GPURoster::rim_protection_best's neutral default
constexpr float kNeutralPlaymakingGravity = 4.5f; // real assists/game baseline; GPURoster::playmaking_gravity_avg's neutral default

// IMPORTANT -- avoiding double-counting against kDefResistanceProbPerRating:
// a team's real season def_rating (the OLS-calibrated, statistically
// significant t=7.63 effect above) is a comprehensive, OUTCOME-based
// measure of that team's real defensive performance -- it already reflects
// whatever real value their rim protectors and ball-hawks actually
// delivered over the season. The per-event magnitudes below were
// originally tuned as if rim_protection_best/help_defense_iq_avg were the
// ONLY source of defensive signal, which meant a team with both a bad real
// def_rating AND a genuinely elite individual shot-blocker (e.g. a
// bottom-of-the-league defense anchored by one historically great rim
// protector -- a real, current case in this league) got suppressed TWICE:
// once by the calibrated team-level gap, and again by the same player's
// raw block total. These magnitudes are now deliberately kept SMALL
// relative to kDefResistanceProbPerRating's real, calibrated swing (often
// several percentage points for a large def_rating gap) -- they add
// tactical TEXTURE (which event fires: a turnover, a contested miss, a
// blocked drive) rather than compounding the TOTAL suppression beyond what
// the data-calibrated team effect already established. The kMinShotProb/
// kMaxShotProb/kMaxTurnoverProb clamps below are also intentionally a real,
// no-team-in-history-shoots-below/above-this-over-a-season range, as a
// hard safety floor/ceiling against any pathological compounding.
constexpr float kBaseTurnoverRate = 0.13f;
constexpr float kTurnoverPerHelpIqPoint = 0.01f;       // per real steal/game above/below neutral
constexpr float kTurnoverPerOnBallDefPoint = 0.0004f;  // per on-ball-defense point above/below neutral
constexpr float kMinTurnoverProb = 0.08f;
constexpr float kMaxTurnoverProb = 0.20f;

