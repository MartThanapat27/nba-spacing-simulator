    std::cout << " " << team_a_name << " average score           : " << stats.avg_score_a << std::endl;
    std::cout << " " << team_b_name << " average score           : " << stats.avg_score_b << std::endl;
    std::cout << " Avg point differential (" << team_a_name << "-" << team_b_name << ") : " << stats.avg_margin << std::endl;
    std::cout << " Point differential std dev  : " << stats.margin_stddev << std::endl;
    std::cout << "========================================================\n" << std::endl;
}

}  // namespace

extern "C" void run_cuda_monte_carlo(const GPUMatchupInput& matchup) {
    std::cout << "\n========================================================" << std::endl;
    std::cout << "   GPU PARALLEL MONTE CARLO MATCHUP SIMULATION (CUDA)" << std::endl;
    std::cout << "   " << matchup.team_a_name << " vs " << matchup.team_b_name
               << " -- " << kSimulationsPerRun << " full 48-minute games" << std::endl;
    std::cout << "========================================================\n" << std::endl;

    const GPURoster& a = matchup.team_a;
    const GPURoster& b = matchup.team_b;

    if (a.num_players <= 0 || b.num_players <= 0) {
        std::cerr << "[CUDA] Empty roster for " << matchup.team_a_name << " and/or "
                   << matchup.team_b_name << " -- skipping GPU simulation." << std::endl;
        return;
    }

    auto start = std::chrono::steady_clock::now();

    DeviceBuffer<float> d_a_fg3_pct, d_a_fg3a, d_a_fg_pct, d_a_ft_pct, d_a_drive_gravity, d_a_usage, d_a_posw, d_a_onball, d_a_pfouls;
    DeviceBuffer<float> d_b_fg3_pct, d_b_fg3a, d_b_fg_pct, d_b_ft_pct, d_b_drive_gravity, d_b_usage, d_b_posw, d_b_onball, d_b_pfouls;
    DeviceBuffer<int> d_out_score_a, d_out_score_b;

    CUDA_CHECK(d_a_fg3_pct.allocate(a.num_players));
    CUDA_CHECK(d_a_fg3a.allocate(a.num_players));
    CUDA_CHECK(d_a_fg_pct.allocate(a.num_players));
    CUDA_CHECK(d_a_ft_pct.allocate(a.num_players));
    CUDA_CHECK(d_a_drive_gravity.allocate(a.num_players));
    CUDA_CHECK(d_a_usage.allocate(a.num_players));
    CUDA_CHECK(d_a_posw.allocate(a.num_players));
    CUDA_CHECK(d_a_onball.allocate(a.num_players));
    CUDA_CHECK(d_a_pfouls.allocate(a.num_players));
    CUDA_CHECK(d_b_fg3_pct.allocate(b.num_players));
    CUDA_CHECK(d_b_fg3a.allocate(b.num_players));
    CUDA_CHECK(d_b_fg_pct.allocate(b.num_players));
    CUDA_CHECK(d_b_ft_pct.allocate(b.num_players));
    CUDA_CHECK(d_b_drive_gravity.allocate(b.num_players));
    CUDA_CHECK(d_b_usage.allocate(b.num_players));
    CUDA_CHECK(d_b_posw.allocate(b.num_players));
    CUDA_CHECK(d_b_onball.allocate(b.num_players));
    CUDA_CHECK(d_b_pfouls.allocate(b.num_players));
    CUDA_CHECK(d_out_score_a.allocate(kSimulationsPerRun));
    CUDA_CHECK(d_out_score_b.allocate(kSimulationsPerRun));

    // GPURoster::on_ball_defense_rating/fg_pct/ft_pct default to a neutral
    // fill if the roster (e.g. an older cached custom-roster JSON built
    // before these fields existed) wasn't sized to match num_players.
    std::vector<float> a_onball_safe = (a.on_ball_defense_rating.size() == static_cast<size_t>(a.num_players))
        ? a.on_ball_defense_rating : std::vector<float>(a.num_players, kNeutralOnBallDefense);
    std::vector<float> b_onball_safe = (b.on_ball_defense_rating.size() == static_cast<size_t>(b.num_players))
        ? b.on_ball_defense_rating : std::vector<float>(b.num_players, kNeutralOnBallDefense);
    std::vector<float> a_fg_pct_safe = (a.fg_pct.size() == static_cast<size_t>(a.num_players))
        ? a.fg_pct : std::vector<float>(a.num_players, kNeutralOverallFgPct);
    std::vector<float> b_fg_pct_safe = (b.fg_pct.size() == static_cast<size_t>(b.num_players))
        ? b.fg_pct : std::vector<float>(b.num_players, kNeutralOverallFgPct);
    std::vector<float> a_ft_pct_safe = (a.ft_pct.size() == static_cast<size_t>(a.num_players))
        ? a.ft_pct : std::vector<float>(a.num_players, kNeutralFtPct);
    std::vector<float> b_ft_pct_safe = (b.ft_pct.size() == static_cast<size_t>(b.num_players))
        ? b.ft_pct : std::vector<float>(b.num_players, kNeutralFtPct);
    std::vector<float> a_drive_gravity_safe = (a.drive_gravity.size() == static_cast<size_t>(a.num_players))
        ? a.drive_gravity : std::vector<float>(a.num_players, kNeutralDriveGravity);
    std::vector<float> b_drive_gravity_safe = (b.drive_gravity.size() == static_cast<size_t>(b.num_players))
        ? b.drive_gravity : std::vector<float>(b.num_players, kNeutralDriveGravity);
    std::vector<float> a_pfouls_safe = (a.personal_fouls_rate.size() == static_cast<size_t>(a.num_players))
        ? a.personal_fouls_rate : std::vector<float>(a.num_players, kNeutralPersonalFouls);
    std::vector<float> b_pfouls_safe = (b.personal_fouls_rate.size() == static_cast<size_t>(b.num_players))
        ? b.personal_fouls_rate : std::vector<float>(b.num_players, kNeutralPersonalFouls);

    CUDA_CHECK(d_a_fg3_pct.upload(a.fg3_pct.data(), a.num_players));
    CUDA_CHECK(d_a_fg3a.upload(a.fg3a.data(), a.num_players));
    CUDA_CHECK(d_a_fg_pct.upload(a_fg_pct_safe.data(), a.num_players));
    CUDA_CHECK(d_a_ft_pct.upload(a_ft_pct_safe.data(), a.num_players));
    CUDA_CHECK(d_a_drive_gravity.upload(a_drive_gravity_safe.data(), a.num_players));
    CUDA_CHECK(d_a_usage.upload(a.usage_rate.data(), a.num_players));
    CUDA_CHECK(d_a_posw.upload(a.position_weight.data(), a.num_players));
    CUDA_CHECK(d_a_onball.upload(a_onball_safe.data(), a.num_players));
    CUDA_CHECK(d_a_pfouls.upload(a_pfouls_safe.data(), a.num_players));
    CUDA_CHECK(d_b_fg3_pct.upload(b.fg3_pct.data(), b.num_players));
    CUDA_CHECK(d_b_fg3a.upload(b.fg3a.data(), b.num_players));
    CUDA_CHECK(d_b_fg_pct.upload(b_fg_pct_safe.data(), b.num_players));
    CUDA_CHECK(d_b_ft_pct.upload(b_ft_pct_safe.data(), b.num_players));
    CUDA_CHECK(d_b_drive_gravity.upload(b_drive_gravity_safe.data(), b.num_players));
    CUDA_CHECK(d_b_usage.upload(b.usage_rate.data(), b.num_players));
    CUDA_CHECK(d_b_posw.upload(b.position_weight.data(), b.num_players));
    CUDA_CHECK(d_b_onball.upload(b_onball_safe.data(), b.num_players));
    CUDA_CHECK(d_b_pfouls.upload(b_pfouls_safe.data(), b.num_players));

    const float ml_prob_shift = matchup.has_ml_margin_bias
        ? static_cast<float>(matchup.ml_margin_bias) * kMlMarginToProbShift
        : 0.0f;
    // Intrinsic home-court effect -- see kHomeCourtPointsOverride's comment
    // block above for why this uses the hand-set override rather than
    // calibrated_constants.h's tiny, statistically-insignificant fitted
    // value. Neither flag set is a neutral-court no-op.
    const float home_prob_shift =
        (matchup.is_team_a_home ? kHomeCourtProbShiftOverride : 0.0f) -
        (matchup.is_team_b_home ? kHomeCourtProbShiftOverride : 0.0f);
    // Intrinsic defensive resistance: always computed from each roster's own
    // real def_rating (no external flag needed -- see GPURoster::def_rating
    // and calibrated_constants.h). Positive when team_b defends worse than
    // team_a, favoring team_a on both ends of the floor; the league average
    // cancels out of this difference, so it's not needed here. This is on by
    // default and isn't gated behind a "has_*" flag -- def_rating already
    // defaults to a neutral league-average value (GPURoster::def_rating's
    // default) when real data isn't available, making this term a no-op in
    // that case.
    const float def_resistance_prob_shift =
        static_cast<float>(engine_calibration::kDefResistanceProbPerRating) * (b.def_rating - a.def_rating);
    const float combined_prob_shift = ml_prob_shift + home_prob_shift + def_resistance_prob_shift;

    const float hot_hand_boost = matchup.has_hot_hand_boost
        ? static_cast<float>(matchup.hot_hand_boost)
        : 1.0f;

    // A back-to-back is treated as ~1 day of rest DISADVANTAGE relative to a
    // normally-rested opponent, so it's applied as the negative of the
    // fitted "shot-prob shift per day of rest advantage" coefficient (see
    // calibrated_constants.h's kFatigueProbPerRestDay comment).
    const float fatigue_prob_penalty_a =
        matchup.is_team_a_b2b ? -static_cast<float>(engine_calibration::kFatigueProbPerRestDay) : 0.0f;
    const float fatigue_gravity_mult_a = matchup.is_team_a_b2b ? kFatigueGravityMultiplier : 1.0f;
    const float fatigue_prob_penalty_b =
        matchup.is_team_b_b2b ? -static_cast<float>(engine_calibration::kFatigueProbPerRestDay) : 0.0f;
    const float fatigue_gravity_mult_b = matchup.is_team_b_b2b ? kFatigueGravityMultiplier : 1.0f;

    const int star_idx_a = argmax_usage(a.usage_rate);
    const int star_idx_b = argmax_usage(b.usage_rate);

    // Team Tactical Archetype (Macro DNA Layer): an explicit
    // --custom-roster override (GPURoster::has_archetype_override) wins;
    // otherwise dynamically derive it from this exact roster's own real
    // season stats. Computed once host-side per batch (not once per
    // thread), same convention as argmax_usage above.
    const int archetype_a = a.has_archetype_override ? a.archetype : derive_team_archetype(a);
    const int archetype_b = b.has_archetype_override ? b.archetype : derive_team_archetype(b);

    const int blocks = (kSimulationsPerRun + kThreadsPerBlock - 1) / kThreadsPerBlock;
    monte_carlo_matchup_kernel<<<blocks, kThreadsPerBlock>>>(
        d_a_fg3_pct.get(), d_a_fg3a.get(), d_a_fg_pct.get(), d_a_ft_pct.get(), d_a_drive_gravity.get(), d_a_usage.get(), d_a_posw.get(), d_a_onball.get(), d_a_pfouls.get(), a.num_players,
        star_idx_a, a.help_defense_iq_avg, a.rim_protection_best, a.playmaking_gravity_avg,
        a.off_reb_gravity_best, a.def_reb_gravity_avg,
        a.help_defense_iq_avg_bench, a.rim_protection_best_bench, a.playmaking_gravity_avg_bench,
        a.off_reb_gravity_best_bench, a.def_reb_gravity_avg_bench,
        d_b_fg3_pct.get(), d_b_fg3a.get(), d_b_fg_pct.get(), d_b_ft_pct.get(), d_b_drive_gravity.get(), d_b_usage.get(), d_b_posw.get(), d_b_onball.get(), d_b_pfouls.get(), b.num_players,
        star_idx_b, b.help_defense_iq_avg, b.rim_protection_best, b.playmaking_gravity_avg,
        b.off_reb_gravity_best, b.def_reb_gravity_avg,
        b.help_defense_iq_avg_bench, b.rim_protection_best_bench, b.playmaking_gravity_avg_bench,
        b.off_reb_gravity_best_bench, b.def_reb_gravity_avg_bench,
        kSimulationsPerRun, combined_prob_shift, hot_hand_boost,
        fatigue_prob_penalty_a, fatigue_gravity_mult_a, fatigue_prob_penalty_b, fatigue_gravity_mult_b,
        archetype_a, archetype_b,
        a.rim_anchor_idx, b.rim_anchor_idx,
        matchup.tuning,
        d_out_score_a.get(), d_out_score_b.get());

    cudaError_t launch_err = cudaGetLastError();
    if (launch_err != cudaSuccess) {
        if (is_toolchain_mismatch(launch_err)) {
            warn_toolchain_mismatch(launch_err);
        } else {
            std::cerr << "[CUDA] Kernel launch failed: " << cudaGetErrorString(launch_err) << std::endl;
        }
        return;
    }

    // Kernel launches are asynchronous -- a PTX JIT failure triggered by the
    // launch above often only surfaces here, at the first synchronization
    // point, rather than from cudaGetLastError() immediately after launch.
    cudaError_t sync_err = cudaDeviceSynchronize();
    if (sync_err != cudaSuccess) {
        if (is_toolchain_mismatch(sync_err)) {
            warn_toolchain_mismatch(sync_err);
        } else {
            std::cerr << "[CUDA] cudaDeviceSynchronize() failed: " << cudaGetErrorString(sync_err) << std::endl;
        }
        return;
    }

    std::vector<int> h_scores_a(kSimulationsPerRun);
    std::vector<int> h_scores_b(kSimulationsPerRun);
    CUDA_CHECK(d_out_score_a.download(h_scores_a.data(), kSimulationsPerRun));
    CUDA_CHECK(d_out_score_b.download(h_scores_b.data(), kSimulationsPerRun));

    auto end = std::chrono::steady_clock::now();
    double elapsed_ms = std::chrono::duration<double, std::milli>(end - start).count();

    BatchStats stats = aggregate_results(h_scores_a, h_scores_b);
    print_gpu_batch_summary(matchup.team_a_name, matchup.team_b_name, stats, elapsed_ms,
                             a.def_rating, b.def_rating,
                             a.rim_protection_best, b.rim_protection_best,
                             a.help_defense_iq_avg, b.help_defense_iq_avg,
                             a.playmaking_gravity_avg, b.playmaking_gravity_avg,
                             archetype_a, archetype_b,
                             matchup.has_ml_margin_bias, matchup.ml_margin_bias,
                             matchup.has_hot_hand_boost, matchup.hot_hand_boost,
                             matchup.is_team_a_home, matchup.is_team_b_home,
                             matchup.is_team_a_b2b, matchup.is_team_b_b2b);
}
